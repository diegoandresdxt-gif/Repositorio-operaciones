numero1,numero2 = map(int,input("Ingrese dos números: ").split())

suma = numero1 + numero2
resta = numero1 - numero2
multiplicacion = numero1 * numero2
division = numero1 / numero2
resultadosuma = suma + resta + multiplicacion + division


print("La suma de los dos números es igual a: ", suma)
print("La resta de los dos números es igual a: ", resta)
print("La multiplicacion de los dos números es igual a: ", multiplicacion)
print("La división de los dos números es igual a: ", division)

print("La suma de los resultados es: ", resultadosuma)
